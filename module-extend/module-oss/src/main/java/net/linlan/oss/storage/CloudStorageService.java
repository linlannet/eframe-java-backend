package net.linlan.oss.storage;

import java.io.InputStream;

import net.linlan.commons.core.FilePathUtils;
import net.linlan.oss.config.CloudStorageConfig;

/**
 * 云存储(支持七牛、阿里云、腾讯云、又拍云)
 * @author Linlan
 * CreateTime 2017-03-25 14:58
 */
public abstract class CloudStorageService {

    /**
     * 云存储配置信息
     */
    public CloudStorageConfig config;

    /**
     * 文件路径
     * @param prefix 前缀
     * @param suffix 后缀
     * @return 返回上传路径
     */
    public String getPath(String prefix, String suffix) {
        return FilePathUtils.getPathOfDay(prefix, suffix);
    }

    /**
     * 文件上传
     * @param data    文件字节数组
     * @param path    文件路径，包含文件名
     * @return        返回http地址
     */
    public abstract String upload(byte[] data, String path);

    /**
     * 文件上传
     * @param data     文件字节数组
     * @param suffix   后缀
     * @return         返回http地址
     */
    public abstract String uploadSuffix(byte[] data, String suffix);

    /**
     * 文件上传
     * @param inputStream   字节流
     * @param path          文件路径，包含文件名
     * @return              返回http地址
     */
    public abstract String upload(InputStream inputStream, String path);

    /**
     * 文件上传
     * @param inputStream  字节流
     * @param suffix       后缀
     * @return             返回http地址
     */
    public abstract String uploadSuffix(InputStream inputStream, String suffix);

}
